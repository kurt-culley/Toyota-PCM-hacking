"""Readable 17140 ignition maps: advance in degrees over rpm and manifold pressure (kPa).

    PYTHONPATH=analysis uv run python -m pcmre.readable17140 --write   # docs/mr2/ignition_maps.md

Units come from the 17140 simulator (tests/test_sim17140.py) and the code (docs/mr2/maps.md):

- columns: RpmWord x 2 - $0200, one column per 256, RpmWord = rpm x 0.32 -> 800-5600 rpm in
  400 rpm steps;
- rows: Load x 4 - offset, one row per 256; Load = 4.98 x kPa + 98.6 in the simulator, which
  rests on the factory PIM curve (V = 0.6 + 0.03 kPa, LIKELY) and on ADC channel 7 being the
  5 V supply (GUESS);
- degrees: 15/64 degree per map count [EMU]. The absolute offset is unknown (docs/mr2/maps.md:
  the fixed-sum anchor gives a 45 degree warm idle, which is not credible), so the tables show
  the map's own contribution, v x 15/64, until a timing light fixes the offset.
"""

from __future__ import annotations

import argparse
import sys

from .roundtrip import ROOT

ROM = ROOT / "AW11 MR2 PCM/89661-17140.bin"
DOC = ROOT / "docs/mr2/ignition_maps.md"
LOAD_PER_KPA, LOAD_AT_0 = 4.98, 98.6
MAPS = {"A": (0xF1EF, "P34 = 1"), "B": (0xF25D, "P34 = 0")}


def degrees(v: int) -> float:
    """The map value's contribution to the advance; the absolute offset is still unknown."""
    return v * 15 / 64


def table(rom: bytes, addr: int) -> tuple[list[int], list[float], list[list[int]]]:
    h = rom[addr - 0xF000 : addr - 0xF000 + 6]
    off1, max1, off2, max2 = h[0] << 8 | h[1], h[2], h[3] << 8 | h[4], h[5]
    cols, rows = max1 + 1, max2 + 1
    rpm = [round((off1 + 256 * c) / 2 / 0.32) for c in range(cols)]
    kpa = [((off2 + 256 * r) / 4 - LOAD_AT_0) / LOAD_PER_KPA for r in range(rows)]
    data = rom[addr - 0xF000 + 6 : addr - 0xF000 + 6 + cols * rows]
    return rpm, kpa, [list(data[r * cols : (r + 1) * cols]) for r in range(rows)]


def build() -> str:
    rom = ROM.read_bytes()
    out = [
        "# MR2 89661-17140: ignition maps in degrees (relative)",
        "",
        "Generated by `python -m pcmre.readable17140 --write`. Do not edit.",
        "",
        "Warm engine, no trims. **Rows: manifold pressure in kPa (absolute). Columns: rpm.**",
        "Heavy load is at the top, like a tuning screen; 100 kPa is about wide-open throttle at sea level.",
        "",
        "**How sure the numbers are:**",
        "- **Degree scale:** 15/64° per map count, measured in the simulator at four speeds "
        "[EMU:tests/test_sim17140.py].",
        "- **Absolute degrees: not known yet.** Each cell is the map's own contribution, value × 15/64°. "
        "The real advance is this plus a constant offset (and the coolant and trim terms). Read the "
        "differences between cells as real degrees; do not read a cell as degrees BTDC. A timing-light "
        "reading at a warm idle with T open, next to the serial link's map value, fixes the offset.",
        "- **kPa per row:** from the factory MAP-sensor curve (LIKELY) and the assumption that ADC "
        "channel 7 is the 5 V supply (GUESS).",
        "",
    ]
    for name, (addr, sel) in MAPS.items():
        rpm, kpa, rows = table(rom, addr)
        out += [
            f"## Map {name} `${addr:04X}` ({sel})",
            "",
            "| kPa \\ rpm | " + " | ".join(str(r) for r in rpm) + " |",
            "|---|" + "---|" * len(rpm),
        ]
        for r in range(len(rows) - 1, -1, -1):
            out.append(f"| **{kpa[r]:.0f}** | " + " | ".join(f"{degrees(v):.1f}" for v in rows[r]) + " |")
        out.append("")
    out += [
        "Between sites the ECU interpolates in both rpm and pressure. Outside the table it holds the edge values.",
        "On a naturally aspirated engine the manifold cannot exceed about 100 kPa. If the kPa scale holds, "
        "100 kPa interpolates between the 91 and 104 kPa rows and the 117 and 130 kPa rows are never used; "
        "the scale itself is in doubt (maps.md).",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    md = build()
    if a.write:
        DOC.write_text(md)
        print(f"wrote {DOC.relative_to(ROOT)}")
    else:
        print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
